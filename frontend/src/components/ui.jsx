export function RiskBadge({ level }) {
  const map = {
    'LOW':       'risk-low',
    'MEDIUM':    'risk-medium',
    'HIGH':      'risk-high',
    'VERY HIGH': 'risk-very-high',
  }
  return (
    <span
      className={map[level] || 'risk-low'}
      style={{
        padding: '4px 12px',
        borderRadius: 20,
        fontSize: 12,
        fontWeight: 700,
        letterSpacing: 0.5,
      }}
    >
      {level}
    </span>
  )
}

